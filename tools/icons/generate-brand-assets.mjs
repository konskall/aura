// Deterministic conversion of original brand artwork; no theme recoloring.
// Optional first/second arguments import the original Aoraton/Google PNGs.
import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import { createRequire } from 'node:module';

const root = process.cwd();
const require = createRequire(path.join(root, '.tools', 'icon-build', 'package.json'));
const { Resvg } = require('@resvg/resvg-js');
const { PNG } = require('pngjs');
const directory = path.join(root, 'shared', 'assets', 'branding');
fs.mkdirSync(directory, { recursive: true });

const arrays = [];
const assets = [];
const sha256 = (bytes) => crypto.createHash('sha256').update(bytes).digest('hex');

function appendAsset(name, id, png, source, sourceBytes) {
  const bgra = [];
  for (let offset = 0; offset < png.data.length; offset += 4) {
    bgra.push(png.data[offset + 2], png.data[offset + 1], png.data[offset], png.data[offset + 3]);
  }
  const rows = [];
  for (let offset = 0; offset < bgra.length; offset += 16) {
    rows.push(`    ${bgra.slice(offset, offset + 16).map(value => `0x${value.toString(16).padStart(2, '0').toUpperCase()}`).join(', ')},`);
  }
  arrays.push(`static const uint8_t ${name}_map[] = {\n${rows.join('\n')}\n};\n\nconst lv_image_dsc_t ${name} = {\n    .header = {\n        .magic = LV_IMAGE_HEADER_MAGIC,\n        .cf = LV_COLOR_FORMAT_ARGB8888,\n        .flags = 0,\n        .w = ${png.width},\n        .h = ${png.height},\n        .stride = ${png.width * 4},\n        .reserved_2 = 0,\n    },\n    .data_size = sizeof(${name}_map),\n    .data = ${name}_map,\n    .reserved = nullptr,\n    .reserved_2 = nullptr,\n};`);
  assets.push({ id, width: png.width, height: png.height, source, source_sha256: sha256(sourceBytes), bytes: bgra.length });
}

const squareBrands = [
  { id: 'aoraton', size: 96, file: 'aoraton-logo.png', source: 'https://aoraton.com/favicon-96x96.png' },
  { id: 'google', size: 32, file: 'google-g.png', source: 'https://developers.google.com/static/identity/images/g-logo.png' },
];
for (const [index, brand] of squareBrands.entries()) {
  const original = path.join(directory, brand.file);
  if (process.argv[index + 2]) fs.copyFileSync(path.resolve(process.argv[index + 2]), original);
  const bytes = fs.readFileSync(original);
  const rounded = brand.id === 'aoraton';
  const clip = rounded ? `<defs><clipPath id="corners"><rect width="${brand.size}" height="${brand.size}" rx="${brand.size / 4}"/></clipPath></defs>` : '';
  const svg = `<svg xmlns="http://www.w3.org/2000/svg" width="${brand.size}" height="${brand.size}">${clip}<image href="data:image/png;base64,${bytes.toString('base64')}" width="${brand.size}" height="${brand.size}" preserveAspectRatio="xMidYMid meet"${rounded ? ' clip-path="url(#corners)"' : ''}/></svg>`;
  const png = PNG.sync.read(new Resvg(svg).render().asPng());
  appendAsset(`aura_brand_${brand.id}`, brand.id, png, brand.source, bytes);
}

// The owner-approved Aura wordmark stays vector-authored. The large PNG is
// retained only as the supplied transparent reference and is never compiled.
const auraSvgPath = path.join(directory, 'source', 'Aura_Selas.svg');
const auraPngPath = path.join(directory, 'source', 'Aura_Selas_Transparent.png');
const auraSvg = fs.readFileSync(auraSvgPath);
const auraReference = fs.readFileSync(auraPngPath);
const referencePng = PNG.sync.read(auraReference);
const auraTargets = [
  { id: 'aura-compact', name: 'aura_brand_aura_compact', width: 144, height: 53 },
  { id: 'aura-hero', name: 'aura_brand_aura_hero', width: 176, height: 65 },
];
for (const target of auraTargets) {
  const png = PNG.sync.read(new Resvg(auraSvg, { fitTo: { mode: 'width', value: target.width } }).render().asPng());
  if (png.width !== target.width || png.height !== target.height) {
    throw new Error(`${target.id}: expected ${target.width}x${target.height}, got ${png.width}x${png.height}`);
  }
  appendAsset(target.name, target.id, png, 'source/Aura_Selas.svg', auraSvg);
}

const declarations = [
  'LV_IMAGE_DECLARE(aura_brand_aoraton);',
  'LV_IMAGE_DECLARE(aura_brand_google);',
  'LV_IMAGE_DECLARE(aura_brand_aura_compact);',
  'LV_IMAGE_DECLARE(aura_brand_aura_hero);',
];
fs.writeFileSync(path.join(directory, 'aura_brand_assets.hpp'),
  `#pragma once\n\n#include "lvgl.h"\n\n${declarations.join('\n')}\n`);
fs.writeFileSync(path.join(directory, 'aura_brand_assets.cpp'),
  '// Generated by tools/icons/generate-brand-assets.mjs from original brand artwork.\n#include "aura_brand_assets.hpp"\n\n' + arrays.join('\n\n') + '\n');
fs.writeFileSync(path.join(directory, 'manifest.json'), JSON.stringify({
  schema: 'aura.brand-assets.v2',
  format: 'ARGB8888',
  reference: {
    file: 'source/Aura_Selas_Transparent.png',
    width: referencePng.width,
    height: referencePng.height,
    sha256: sha256(auraReference),
    compiled: false,
  },
  assets,
}, null, 2) + '\n');
console.log(`Generated ${assets.length} full-color brand assets (${assets.reduce((sum, asset) => sum + asset.bytes, 0)} bytes; Aura ${auraTargets.reduce((sum, target) => sum + target.width * target.height * 4, 0)} bytes).`);
